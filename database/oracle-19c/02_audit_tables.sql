CREATE TABLE CLIENTE (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CPF VARCHAR2(11 CHAR) NOT NULL,
    NOME VARCHAR2(200 CHAR) NOT NULL,
    EMAIL VARCHAR2(255 CHAR),
    CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP(6)
);

CREATE TABLE AUDIT_LOG (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EVENT_TIMESTAMP TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    NM_USUARIO_APLICACAO VARCHAR2(100 CHAR) NOT NULL,
    NR_IP_APLICACAO VARCHAR2(45 CHAR) NOT NULL,
    NM_APLICATIVO VARCHAR2(50 CHAR),
    OPERATION VARCHAR2(10 CHAR) NOT NULL,
    TABLE_NAME VARCHAR2(128 CHAR) NOT NULL,
    RECORD_ID VARCHAR2(200 CHAR),
    OLD_VALUES CLOB,
    NEW_VALUES CLOB
);

CREATE INDEX IDX_AUDIT_LOG_TIMESTAMP ON AUDIT_LOG (EVENT_TIMESTAMP);
CREATE INDEX IDX_AUDIT_LOG_USER_TIMESTAMP ON AUDIT_LOG (NM_USUARIO_APLICACAO, EVENT_TIMESTAMP);
