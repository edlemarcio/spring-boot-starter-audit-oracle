-- Execute as the application schema owner (or adapt the package owner and grants).
-- The schema needs CREATE PROCEDURE and CREATE CONTEXT privileges.
-- Keep EXECUTE on this package restricted to the trusted application database user.

CREATE OR REPLACE PACKAGE PKG_AUDITORIA_CONTEXT AS
    PROCEDURE SET_CONTEXT(
        P_CPF IN VARCHAR2,
        P_NOME IN VARCHAR2,
        P_REQUEST_ID IN VARCHAR2
    );

    PROCEDURE CLEAR_CONTEXT;
END PKG_AUDITORIA_CONTEXT;
/

CREATE OR REPLACE PACKAGE BODY PKG_AUDITORIA_CONTEXT AS

    PROCEDURE SET_CONTEXT(
        P_CPF IN VARCHAR2,
        P_NOME IN VARCHAR2,
        P_REQUEST_ID IN VARCHAR2
    ) IS
        V_CPF VARCHAR2(11);
    BEGIN
        V_CPF := REGEXP_REPLACE(P_CPF, '[^0-9]', '');

        IF V_CPF IS NULL OR LENGTH(V_CPF) <> 11 THEN
            RAISE_APPLICATION_ERROR(-20001, 'Audit CPF must contain 11 digits');
        END IF;

        IF P_NOME IS NULL OR LENGTH(TRIM(P_NOME)) = 0 OR LENGTH(P_NOME) > 200 THEN
            RAISE_APPLICATION_ERROR(-20002, 'Audit name is required and must be at most 200 characters');
        END IF;

        IF P_REQUEST_ID IS NULL OR LENGTH(TRIM(P_REQUEST_ID)) = 0 OR LENGTH(P_REQUEST_ID) > 128 THEN
            RAISE_APPLICATION_ERROR(-20003, 'Audit request id is required and must be at most 128 characters');
        END IF;

        DBMS_SESSION.SET_CONTEXT('CTX_AUDITORIA', 'CPF', V_CPF);
        DBMS_SESSION.SET_CONTEXT('CTX_AUDITORIA', 'NOME', TRIM(P_NOME));
        DBMS_SESSION.SET_CONTEXT('CTX_AUDITORIA', 'REQUEST_ID', TRIM(P_REQUEST_ID));
    END SET_CONTEXT;

    PROCEDURE CLEAR_CONTEXT IS
    BEGIN
        DBMS_SESSION.CLEAR_CONTEXT('CTX_AUDITORIA', NULL);
    END CLEAR_CONTEXT;

END PKG_AUDITORIA_CONTEXT;
/

CREATE OR REPLACE CONTEXT CTX_AUDITORIA USING PKG_AUDITORIA_CONTEXT;
/
