CREATE OR REPLACE TRIGGER TRG_CLIENTE_AUDIT
AFTER INSERT OR UPDATE OR DELETE ON CLIENTE
FOR EACH ROW
DECLARE
    V_USER VARCHAR2(100 CHAR);
    V_IP VARCHAR2(45 CHAR);
    V_APPLICATION VARCHAR2(50 CHAR);
    V_OPERATION VARCHAR2(10);
    V_RECORD_ID VARCHAR2(200);
    V_OLD_VALUES CLOB;
    V_NEW_VALUES CLOB;
BEGIN
    V_USER := SUBSTR(NVL(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'),
                         SYS_CONTEXT('USERENV', 'SESSION_USER')), 1, 100);
    V_IP := SUBSTR(NVL(SYS_CONTEXT('USERENV', 'CLIENT_INFO'),
                       NVL(SYS_CONTEXT('USERENV', 'IP_ADDRESS'), '0.0.0.0')), 1, 45);
    V_APPLICATION := SUBSTR(SYS_CONTEXT('USERENV', 'MODULE'), 1, 50);

    IF INSERTING THEN
        V_OPERATION := 'INSERT';
        V_RECORD_ID := TO_CHAR(:NEW.ID);
        SELECT JSON_OBJECT(
            'id' VALUE :NEW.ID,
            'cpf' VALUE :NEW.CPF,
            'nome' VALUE :NEW.NOME,
            'email' VALUE :NEW.EMAIL
            RETURNING CLOB
        ) INTO V_NEW_VALUES FROM DUAL;
    ELSIF UPDATING THEN
        V_OPERATION := 'UPDATE';
        V_RECORD_ID := TO_CHAR(:NEW.ID);
        SELECT JSON_OBJECT(
            'id' VALUE :OLD.ID,
            'cpf' VALUE :OLD.CPF,
            'nome' VALUE :OLD.NOME,
            'email' VALUE :OLD.EMAIL
            RETURNING CLOB
        ) INTO V_OLD_VALUES FROM DUAL;
        SELECT JSON_OBJECT(
            'id' VALUE :NEW.ID,
            'cpf' VALUE :NEW.CPF,
            'nome' VALUE :NEW.NOME,
            'email' VALUE :NEW.EMAIL
            RETURNING CLOB
        ) INTO V_NEW_VALUES FROM DUAL;
    ELSIF DELETING THEN
        V_OPERATION := 'DELETE';
        V_RECORD_ID := TO_CHAR(:OLD.ID);
        SELECT JSON_OBJECT(
            'id' VALUE :OLD.ID,
            'cpf' VALUE :OLD.CPF,
            'nome' VALUE :OLD.NOME,
            'email' VALUE :OLD.EMAIL
            RETURNING CLOB
        ) INTO V_OLD_VALUES FROM DUAL;
    END IF;

    INSERT INTO AUDIT_LOG (
        NM_USUARIO_APLICACAO, NR_IP_APLICACAO, NM_APLICATIVO, OPERATION, TABLE_NAME,
        RECORD_ID, OLD_VALUES, NEW_VALUES
    ) VALUES (
        V_USER, V_IP, V_APPLICATION, V_OPERATION, 'CLIENTE',
        V_RECORD_ID, V_OLD_VALUES, V_NEW_VALUES
    );
END;
